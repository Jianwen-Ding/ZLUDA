#!/usr/bin/env python3
"""Generate f64_to_i32.ptx: cvt.{rni,rmi,rpi,rzi}.s32.f64 and .u32.f64 of 2,048 doubles: halves and quarters of
integers and those values one ulp either way, the ends of the 32-bit ranges and one ulp around them, small values
(|x| < 1, denormals, zeros), infinities, NaNs (s32 only: ZLUDA gives INT_MIN; the u32 conversions read the inputs with NaNs as 0) and random values. Expected values
from Python: the value rounded (to nearest even, down, up, toward zero) and saturated to the integer's range.
usage: f64_to_i32.py OUT.ptx"""
import math, random, struct, sys

random.seed(29)
d2u = lambda x: struct.unpack('<Q', struct.pack('<d', x))[0]
u2d = lambda u: struct.unpack('<d', struct.pack('<Q', u))[0]
up = lambda x: math.nextafter(x, math.inf)
dn = lambda x: math.nextafter(x, -math.inf)

vals = []
for k in [0, 1, 2, 3, 7, 100, 12345, 2**20 + 1, 2**30, 2**31 - 2, 2**31 - 1, 2**31, 2**32 - 1, 2**32]:
    for s in (1, -1):
        for f in (0.0, 0.25, 0.5, 0.75):
            x = s * (k + f)
            vals += [x, up(x), dn(x)]
vals += [0.0, -0.0, 5e-324, -5e-324, 2.2250738585072014e-308, -1e-300, 0.49999999999999994, -0.49999999999999994,
         math.inf, -math.inf, 1e300, -1e300, 2.0**52, 2.0**52 + 1, -(2.0**53)]
while len(vals) < 2048:
    r = random.random()
    if r < .4:
        x = random.uniform(-2**32, 2**32)
    elif r < .6:
        x = float(random.randint(-2**31, 2**32)) + random.choice([.5, -.5, .25, .75])
    elif r < .8:
        x = random.uniform(-3, 3)
    else:
        x = u2d(random.getrandbits(64) & 0x7fefffffffffffff | (random.getrandbits(1) << 63))
    vals.append(x)
vals = vals[:2048]
NAN = 0x7ff8000000000001
bits = [d2u(x) for x in vals]
bits[-8:] = [NAN, NAN | (1 << 63), 0x7ff0000000000001, 0xfff8000000000000] + bits[-4:]


def conv(b, mode, signed):
    x = u2d(b)
    if math.isnan(x):
        return 0x80000000 if signed else None
    if math.isinf(x):
        v = x
    else:
        v = {'rni': lambda t: float(round(t)), 'rmi': math.floor, 'rpi': math.ceil, 'rzi': math.trunc}[mode](x)
    lo, hi = (-2**31, 2**31 - 1) if signed else (0, 2**32 - 1)
    v = lo if v <= lo else hi if v >= hi else int(v)
    return v & 0xffffffff


MODES = ['rni', 'rmi', 'rpi', 'rzi']
h = lambda xs: ", ".join(str(x) for x in xs)
L = ["// GENERATED by gen/f64_to_i32.py -- cvt.{rni,rmi,rpi,rzi}.{s32,u32}.f64",
     ".version 8.0\n.target sm_80\n.address_size 64\n",
     """.visible .entry k(.param .u64 pa, .param .u64 pu, .param .u64 po)
{
    .reg .u64 %pa, %pu, %po, %t; .reg .u32 %tid, %c, %n, %r; .reg .f64 %d, %du;
    ld.param.u64 %pa, [pa]; ld.param.u64 %pu, [pu]; ld.param.u64 %po, [po];
    mov.u32 %tid, %tid.x; mov.u32 %c, %ctaid.x; mov.u32 %n, %ntid.x; mad.lo.u32 %tid, %c, %n, %tid;
    mul.wide.u32 %t, %tid, 8; add.u64 %pa, %pa, %t; add.u64 %pu, %pu, %t;
    mul.wide.u32 %t, %tid, 32; add.u64 %po, %po, %t;
    ld.global.f64 %d, [%pa]; ld.global.f64 %du, [%pu];"""]
i = 0
for signed in (True, False):
    for m in MODES:
        L.append(f"    cvt.{m}.{'s32' if signed else 'u32'}.f64 %r, {'%d' if signed else '%du'}; st.global.u32 [%po+{4 * i}], %r;")
        i += 1
L.append("    ret;\n}\n")
ubits = [0 if math.isnan(u2d(b)) else b for b in bits]
exp = []
for b, ub in zip(bits, ubits):
    for signed in (True, False):
        for m in MODES:
            exp.append(conv(b if signed else ub, m, signed))
L.append(f".buffer A .u64 = {{ {h(bits)} }};")
L.append(f".buffer U .u64 = {{ {h(ubits)} }};")
L.append(f".buffer O .u32 [{len(exp)}];")
L.append(f".launch k <<< 16, 128 >>> (A, U, O);")
L.append(f".expect O .u32 = {{ {h(exp)} }};")
open(sys.argv[1], "w").write("\n".join(L) + "\n")
