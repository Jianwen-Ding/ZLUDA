#!/usr/bin/env python3
"""Generate agx_tests/approx-f64-form.ptx (see its header).  usage: gen_approx_f64_form.py > agx_tests/approx-f64-form.ptx"""
import random, struct, math
random.seed(9)
def d2b(x): return struct.unpack('<Q', struct.pack('<d', x))[0]
INF=float('inf')
# special-value tables (PTX ISA 9.4 9.7.3.17 rcp.approx.ftz.f64, 9.7.3.20 rsqrt.approx.ftz.f64): input upper word -> result upper word
SUBP, SUBN = 0x000fffff00000000 | 0x12345, 0x8000000100000000
RCP = [(d2b(-INF), d2b(-0.0)), (SUBN, d2b(-INF)), (d2b(-0.0), d2b(-INF)), (d2b(0.0), d2b(INF)), (SUBP, d2b(INF)),
       (d2b(INF), d2b(0.0)), (0x7ff8000000000001, 0x7fffffff00000000), (0xfff8000100000000, 0x7fffffff00000000),
       # a NaN only in its low word: the upper word is -Inf, the only one read
       (0xfff0000000000123, d2b(-0.0))]
RSQ = [(d2b(-INF), 0x7fffffff00000000), (SUBN, d2b(-INF)), (d2b(-0.0), d2b(-INF)), (d2b(0.0), d2b(INF)),
       (SUBP, d2b(INF)), (d2b(INF), d2b(0.0)), (0x7ff8000000000001, 0x7fffffff00000000)]
def rnd(neg):
    e = random.randint(-1000, 1000)
    x = random.uniform(1, 2) * 2.0 ** e
    return -x if neg and random.random() < .5 else x
out = []
out.append("""// rcp.approx.ftz.f64 and rsqrt.approx.ftz.f64 (PTX ISA 9.4 9.7.3.17, 9.7.3.20): the ISA bounds no error ("a fast,
// gross approximation") but fixes the form: only a[63:32] is read, d[31:0] is 0, input NaNs give the canonical
// 0x7fffffff00000000, subnormals flush, and the special-value tables. Generated by gen_approx_f64_form.py.
.version 7.0
.target sm_80
.address_size 64""")
for name, insn in (("krcp", "rcp.approx.ftz.f64"), ("krsq", "rsqrt.approx.ftz.f64")):
    out.append(""".visible .entry %s(.param .u64 px, .param .u64 py)
{
    .reg .b32 %%r0, %%lo, %%hi; .reg .b64 %%rd<8>; .reg .f64 %%fd<4>;
    mov.u32 %%r0, %%tid.x; mul.wide.u32 %%rd1, %%r0, 8;
    ld.param.u64 %%rd2, [px]; add.s64 %%rd2, %%rd2, %%rd1; ld.global.f64 %%fd1, [%%rd2];
    %s %%fd2, %%fd1;
    // the same upper word with another lower word gives the same result
    mov.b64 {%%lo, %%hi}, %%fd1; xor.b32 %%lo, %%lo, 0x5a5a5a5a; mov.b64 %%fd3, {%%lo, %%hi};
    %s %%fd3, %%fd3;
    mov.b64 %%rd4, %%fd2; mov.b64 %%rd5, %%fd3; xor.b64 %%rd5, %%rd5, %%rd4;
    // d[31:0] is 0 and the results agree: the low word and the difference ORed
    cvt.u32.u64 %%lo, %%rd4; cvt.u32.u64 %%hi, %%rd5; shr.u64 %%rd6, %%rd5, 32; cvt.u32.u64 %%r0, %%rd6;
    or.b32 %%lo, %%lo, %%hi; or.b32 %%lo, %%lo, %%r0;
    mul.wide.u32 %%rd1, %%r0, 0; mov.u32 %%r0, %%tid.x; mul.wide.u32 %%rd1, %%r0, 4;
    ld.param.u64 %%rd3, [py]; add.s64 %%rd3, %%rd3, %%rd1; st.global.u32 [%%rd3], %%lo;
    ret;
}""" % (name, insn, insn))
out.append(""".visible .entry %s(.param .u64 px, .param .u64 py)
{
    .reg .b32 %%r0; .reg .b64 %%rd<4>; .reg .f64 %%fd<3>;
    mov.u32 %%r0, %%tid.x; mul.wide.u32 %%rd1, %%r0, 8;
    ld.param.u64 %%rd2, [px]; add.s64 %%rd2, %%rd2, %%rd1; ld.global.f64 %%fd1, [%%rd2];
    %s %%fd2, %%fd1;
    ld.param.u64 %%rd3, [py]; add.s64 %%rd3, %%rd3, %%rd1; st.global.f64 [%%rd3], %%fd2;
    ret;
}""" % ("srcp", "rcp.approx.ftz.f64"))
out.append(out[-1].replace("srcp", "srsq").replace("rcp.approx", "rsqrt.approx"))
xs = [d2b(rnd(True)) for _ in range(96)]
ys = [d2b(rnd(False)) for _ in range(96)]
for k, v in (("krcp", xs), ("krsq", ys)):
    out.append(".buffer X%s .u64 = { %s };\n.buffer Y%s .u32 [%d];\n.launch %s <<< 1, %d >>> (X%s, Y%s);\n.expect Y%s .u32 = { %s };"
               % (k, ', '.join(map(str, v)), k, len(v), k, len(v), k, k, k, ', '.join(['0'] * len(v))))
for k, t in (("srcp", RCP), ("srsq", RSQ)):
    out.append(".buffer X%s .u64 = { %s };\n.buffer Y%s .u64 [%d];\n.launch %s <<< 1, %d >>> (X%s, Y%s);\n.expect Y%s .u64 = { %s };"
               % (k, ', '.join(str(a) for a, _ in t), k, len(t), k, len(t), k, k, k, ', '.join(str(b) for _, b in t)))
print('\n'.join(out))
