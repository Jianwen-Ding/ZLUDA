#!/usr/bin/env python3
"""Replay our captured inference primitives in AGX-Performance-Simulator and compare with NumPy.
Inputs are captures generated by tests/test_gpu.py; no vendor objects or engines are accepted or needed.
"""
import argparse
import os
from pathlib import Path
import re
import subprocess
import numpy as np

p=argparse.ArgumentParser();p.add_argument('captures',type=Path);p.add_argument('--agx-run',required=True);a=p.parse_args()
passed=[]
for folder in sorted(a.captures.iterdir()):
    replay=folder/'replay.sh'
    if not replay.is_file():continue
    text=replay.read_text();m=re.search(r'# kernel (agx_infer_\w+).* arguments \[([^\]]+)\]',text)
    if not m:continue
    name=m.group(1);args=[int(v.strip(),0) for v in m.group(2).split(',')]
    subprocess.run(['sh',str(replay.resolve())],env={**os.environ,'AGX_RUN':a.agx_run},check=True,stdout=subprocess.PIPE,stderr=subprocess.PIPE,timeout=30)
    regions=[]
    for line in (folder/'regions.txt').read_text().splitlines():
        file,base,size=line.split();regions.append((int(base,0),int(size),file))
    def view(ptr,count,dtype=np.float32,after=False):
        size=np.dtype(dtype).itemsize*count
        for base,n,file in regions:
            if base<=ptr and ptr+size<=base+n:
                path=folder/(file.replace('.bin','.out') if after else file)
                return np.frombuffer(path.read_bytes(),dtype=dtype,count=count,offset=ptr-base).copy()
        raise AssertionError((name,hex(ptr),count,'outside captured regions'))
    if name=='agx_infer_binary':
        x,b,y,meta,n,rank,op,relu=args;desc=view(meta,rank*3,np.int32);shape=tuple(desc[:rank]);coords=np.indices(shape).reshape(rank,-1) if rank else np.zeros((0,1),dtype=np.int32)
        ai=np.sum(coords*desc[rank:2*rank,None],axis=0,dtype=np.int64);bi=np.sum(coords*desc[2*rank:3*rank,None],axis=0,dtype=np.int64)
        av=view(x,int(np.max(ai))+1)[ai];bv=view(b,int(np.max(bi))+1)[bi]
        reference=[lambda:av+bv,lambda:av*bv,lambda:av-bv,lambda:av-bv,lambda:np.maximum(av,bv),lambda:np.minimum(av,bv)][op]()
        if op==3:reference=av/bv
        if relu:reference=np.maximum(reference,0)
    elif name=='agx_infer_unary':
        x,y,n,op=args;v=view(x,n)
        reference=[lambda:np.maximum(v,0),lambda:1/(1+np.exp(-v)),lambda:np.tanh(v),lambda:v][op]()
    elif name in ['agx_infer_softmax','agx_infer_softmax_simd']:
        if len(args)==4:x,y,rows,channels=args;inner=1
        else:x,y,rows,channels,inner=args
        n=rows*channels;v=view(x,n).reshape(rows//inner,channels,inner)
        e=np.exp(v-v.max(axis=1,keepdims=True));reference=(e/e.sum(axis=1,keepdims=True)).reshape(-1)
    elif name=='agx_infer_transpose':
        x,y,meta,n,rank=args;desc=view(meta,rank*2,np.int32);shape=tuple(desc[:rank]);coords=np.indices(shape).reshape(rank,-1) if rank else np.zeros((0,1),dtype=np.int32)
        indices=np.sum(coords*desc[rank:,None],axis=0,dtype=np.int64);reference=view(x,int(np.max(indices))+1)[indices]
    elif name=='agx_infer_concat':
        x,y,n,chunk,span,offset=args;source=view(x,n);indices=(np.arange(n)//chunk)*span+offset+np.arange(n)%chunk
        # Only this concat input was launched in the capture, so other slices keep their initial values.
        n=int(np.max(indices))+1;reference=view(y,n);reference[indices]=source
    elif name=='agx_infer_pool':
        x,y,n,H,W,P,Q,R,S,ph,pw,sh,sw,kind,include=args;nc=n//(P*Q);v=view(x,nc*H*W).reshape(nc,H,W);reference=np.empty(n,dtype=np.float32)
        for i in range(n):
            c=i//(P*Q);pp=(i//Q)%P;qq=i%Q
            vals=[v[c,h,w] for h in range(pp*sh-ph,pp*sh-ph+R) for w in range(qq*sw-pw,qq*sw-pw+S) if 0<=h<H and 0<=w<W]
            reference[i]=max(vals,default=-np.inf) if kind==0 else sum(vals)/max(1,R*S if include else len(vals))
    else:raise AssertionError(name)
    np.testing.assert_allclose(view(y,n,after=True),reference,rtol=5e-4,atol=3e-5,equal_nan=True,err_msg=name)
    passed.append(name);print('PASS',name)
assert len(set(passed))==7,passed
print('PASS: seven portable inference kernels on the simulator')
