#!/usr/bin/env python3
"""Generate prmt_const.ptx: prmt.b32 (default mode) with constant selectors, which the AGX backend builds from
16-bit halves (AGXCodeGenPrepare permuteBytes: bit-field inserts of bytes, sign fills). 320 selectors (every selector
of one repeated nibble, the 128 low-half pairs of sign-free nibbles, random ones with and without sign bits) on 32
operand pairs (edges and random), each selector on its own operands (a and b xor constants, so that
the byte trees are not shared). Expected values from the PTX ISA's definition of prmt: each selector nibble picks a
byte of {b, a} (a bytes 0-3, b bytes 4-7) by its low three bits, and with bit 3 replicates that byte's sign bit.
usage: prmt_const.py OUT.ptx"""
import random, sys

random.seed(23)


def prmt(a, b, s):
    src = [(a >> (8 * i)) & 255 for i in range(4)] + [(b >> (8 * i)) & 255 for i in range(4)]
    r = 0
    for k in range(4):
        n = (s >> (4 * k)) & 15
        v = src[n & 7]
        if n & 8:
            v = 255 if v & 128 else 0
        r |= v << (8 * k)
    return r


sels = []
for n in range(16):
    sels.append(n * 0x1111)
for lo in range(8):
    for hi in range(8):
        for top in (0x10, 0x32):
            sels.append((top << 8) | (hi << 4) | lo)
while len(sels) < 320:
    s = random.getrandbits(16)
    if len(sels) % 2:
        s &= 0x7777
    if s not in sels:
        sels.append(s)
sels = sels[:320]

edges = [0, 0xffffffff, 0x80808080, 0x7f7f7f7f, 0x01234567, 0x89abcdef, 0x00ff00ff, 0xff00ff00]
pairs = [(x, y) for x in edges for y in edges[:2]]
keys = [(random.getrandbits(32), random.getrandbits(32)) for _ in sels]
while len(pairs) < 32:
    pairs.append((random.getrandbits(32), random.getrandbits(32)))

h = lambda xs: ", ".join(str(x) for x in xs)
n = len(sels)
L = ["// GENERATED by gen/prmt_const.py -- prmt.b32 with constant selectors",
     ".version 8.0\n.target sm_80\n.address_size 64\n",
     f""".visible .entry k(.param .u64 pa, .param .u64 pb, .param .u64 po)
{{
    .reg .u64 %pa, %pb, %po, %t; .reg .u32 %tid, %a, %b, %x, %y, %r;
    ld.param.u64 %pa, [pa]; ld.param.u64 %pb, [pb]; ld.param.u64 %po, [po];
    mov.u32 %tid, %tid.x;
    mul.wide.u32 %t, %tid, 4; add.u64 %pa, %pa, %t; add.u64 %pb, %pb, %t;
    mul.wide.u32 %t, %tid, {4 * n}; add.u64 %po, %po, %t;
    ld.global.u32 %a, [%pa]; ld.global.u32 %b, [%pb];"""]
for i, s in enumerate(sels):
    ka, kb = keys[i]
    L.append(f"    xor.b32 %x, %a, {ka}; xor.b32 %y, %b, {kb}; prmt.b32 %r, %x, %y, {s:#06x}; st.global.u32 [%po+{4 * i}], %r;")
L.append("    ret;\n}\n")
L.append(f".buffer A .u32 = {{ {h(p[0] for p in pairs)} }};")
L.append(f".buffer B .u32 = {{ {h(p[1] for p in pairs)} }};")
L.append(f".buffer O .u32 [{n * len(pairs)}];")
L.append(f".launch k <<< 1, 32 >>> (A, B, O);")
L.append(f".expect O .u32 = {{ {h(prmt(a ^ k[0], b ^ k[1], s) for a, b in pairs for s, k in zip(sels, keys))} }};")
open(sys.argv[1], "w").write("\n".join(L) + "\n")
