#!/usr/bin/env python3
"""Generate agx_tests/approx-bounds-16.ptx: the 16-bit approximations of PTX ISA 9.4 (9.7.4.x) on random inputs,
checked against the error bounds it states with .expectbound (agx_ptx_formalization_check.py), and their
special-value tables, scalar and packed (x2: each half on its own):

    ex2.approx.f16{,x2}         2^-9.9 relative          ex2.approx.ftz.bf16{,x2}   2^-7 relative
    tanh.approx.f16{,x2}        2^-10.987 absolute       tanh.approx.bf16{,x2}      2^-8 absolute

ex2.approx.f16 supports subnormal inputs; ex2.approx.ftz.bf16 flushes subnormal inputs and results to
sign-preserving zero; tanh supports subnormals. The exact values are computed in double precision. Inputs are
drawn where the results are normal (a relative bound on a subnormal result would exceed its precision; for
.ftz.bf16 a result within the bound of 2^-126 may fall below it and flush).
    usage: gen_approx_bounds16.py [N] [SEED] > agx_tests/approx-bounds-16.ptx
"""
import math
import random
import struct
import sys

N = int(sys.argv[1]) if len(sys.argv) > 1 else 128
SEED = int(sys.argv[2]) if len(sys.argv) > 2 else 5
random.seed(SEED)
INF, NAN = math.inf, math.nan


def h2b(x):
    try:
        return struct.unpack('<H', struct.pack('<e', x))[0]
    except OverflowError:
        return 0x7c00 if x > 0 else 0xfc00


def b2h(b):
    return struct.unpack('<e', struct.pack('<H', b))[0]


def bf2b(x):
    """x (already a bf16 value, or a special) as bf16 bits."""
    return struct.unpack('<I', struct.pack('<f', x))[0] >> 16


def b2bf(b):
    return struct.unpack('<f', struct.pack('<I', b << 16))[0]


def f16(lo, hi):
    return b2h(h2b(random.uniform(lo, hi)))


def bf16(lo, hi):
    return b2bf(bf2b(random.uniform(lo, hi)) )


def ex2(x):
    return NAN if x != x else (0.0 if x == -INF else (INF if x == INF else 2.0 ** x))


def tanh_(x):
    return NAN if x != x else math.tanh(x)


def flush_bf(x):
    return math.copysign(0.0, x) if x == x and x != 0 and abs(x) < 2.0 ** -126 else x


SPECIAL = [0.0, -0.0, INF, -INF, NAN]
F16_SUB = [b2h(1), b2h(0x8001), b2h(0x3ff), b2h(0x83ff)]   # f16 subnormals
BF_SUB = [b2bf(1), b2bf(0x8001), b2bf(0x7f)]              # bf16 subnormals
# (instruction, format, packed, function, ftz, kind, bound, inputs)
CASES = []
for packed in (False, True):
    x2 = 'x2' if packed else ''
    CASES += [
        (f'ex2.approx.f16{x2}', 'f16', packed, ex2, False, 'rel', '2^-9.9',
         SPECIAL + F16_SUB + [f16(-14, 15.99) for _ in range(N)] + [float(k) for k in range(-14, 16)]),
        (f'ex2.approx.ftz.bf16{x2}', 'bf16', packed, ex2, True, 'rel', '2^-7',
         SPECIAL + BF_SUB + [bf16(-125, 127.9) for _ in range(N)] + [float(k) for k in range(-125, 128, 9)]),
        (f'tanh.approx.f16{x2}', 'f16', packed, tanh_, False, 'abs', '2^-10.987',
         SPECIAL + F16_SUB + [f16(-8, 8) for _ in range(N)] + [f16(-0.01, 0.01) for _ in range(N // 4)]),
        (f'tanh.approx.bf16{x2}', 'bf16', packed, tanh_, False, 'abs', '2^-8',
         SPECIAL + BF_SUB + [bf16(-8, 8) for _ in range(N)] + [bf16(-0.01, 0.01) for _ in range(N // 4)]),
    ]


def lit(x):
    return 'nan' if x != x else ('-inf' if x == -INF else ('inf' if x == INF else repr(x)))


out = ['// Generated by ptx/tools/gen_approx_bounds16.py %d %d: the 16-bit approximations within the error bounds'
       % (N, SEED), '// of PTX ISA 9.4 (.expectbound: agx_ptx_formalization_check.py only)',
       '.version 8.6', '.target sm_90', '.address_size 64', '']
harness = []
for k, (insn, fmt, packed, fun, ftz, kind, bound, xs) in enumerate(CASES):
    enc = h2b if fmt == 'f16' else bf2b
    if len(xs) % 2:
        xs = xs + [1.0]
    w, reg = (4, '%r') if packed else (2, '%h')
    out += ['.visible .entry k%d(.param .u64 px, .param .u64 py)' % k, '{',
            '    .reg .b32 %r<3>; .reg .b16 %h<3>; .reg .b64 %rd<4>;',
            '    mov.u32 %r0, %tid.x; mul.wide.u32 %rd1, %r0, ' + str(w) + ';',
            '    ld.param.u64 %%rd2, [px]; add.s64 %%rd2, %%rd2, %%rd1; ld.global.b%d %s1, [%%rd2];' % (8 * w, reg),
            '    %s %s2, %s1;' % (insn, reg, reg),
            '    ld.param.u64 %%rd3, [py]; add.s64 %%rd3, %%rd3, %%rd1; st.global.b%d [%%rd3], %s2;' % (8 * w, reg),
            '    ret;', '}', '']
    threads = len(xs) // 2 if packed else len(xs)
    assert threads <= 1024
    exact = []
    for x in xs:
        y = fun(flush_bf(x) if ftz else x)
        exact.append(lit(flush_bf(y) if ftz else y))
    harness.append('// ' + insn)
    harness.append('.buffer X%d .u16 = { %s };' % (k, ', '.join(str(enc(x)) for x in xs)))
    harness.append('.buffer Y%d .u16 [%d];' % (k, len(xs)))
    harness.append('.launch k%d <<< 1, %d >>> (X%d, Y%d);' % (k, threads, k, k))
    harness.append('.expectbound Y%d .%s %s %s = { %s };' % (k, fmt, kind, bound, ', '.join(exact)))
print('\n'.join(out + harness))
