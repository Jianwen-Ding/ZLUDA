#!/usr/bin/env python3
"""Generate tma-edge-*.ptx: 2D cp.async.bulk.tensor tile loads and stores whose rows run past the end of the tensor
(dimension 0 and 1), or start before it, with the swizzle modes of the tensor map. They check the emulation's row
copies in 16-byte chunks (whole rows, and the in-bounds chunks of a row past the end) and mode 5's 8-byte flip of a
chunk's halves. Expected values follow the destination-layout tables of the PTX ISA (section 5.5.7, "Swizzling
Modes"), as in PTX-formalization's scripts/gen_tma_swz.py; nothing is recorded from a GPU.
usage: tma_edges.py DIR"""
import os, random, sys

random.seed(11)
h = lambda xs: ", ".join(str(x) for x in xs)
CODES = {'none': 0, '32': 1, '64': 2, '128': 3, '128a32': 4, '128a32f': 5, '128a64': 6}


def perm_chunk(mode, c, line):
    """16-byte chunk c (0..7) of 128-byte line `line` -> destination chunk"""
    if mode == 'none': return c
    if mode == '32': return c ^ (line % 2)
    if mode == '64': return (c & 4) | ((c & 3) ^ (line % 4))
    if mode == '128': return c ^ (line % 8)
    if mode in ('128a32', '128a32f'): return 2 * ((c >> 1) ^ (line % 4)) + (c & 1)
    if mode == '128a64': return c ^ (4 * (line % 2))


def dest(mode, b):
    """the shared byte of byte b of the dense box image"""
    line, c, off = b // 128, (b // 16) % 8, b % 16
    d = line * 128 + perm_chunk(mode, c, line) * 16 + off
    if mode == '128a32f' and line % 2 == 1:
        d ^= 8  # adjacent 8-byte halves of the 16-byte chunk swapped on odd lines
    return d


def load_test(out, name, mode, dtype, fill, dims, box, coords, eb, nan_bits=None):
    vals = [random.randint(1, 60000) if eb == 2 else random.getrandbits(32) for _ in range(dims[0] * dims[1])]
    img = []
    for r in range(box[1]):
        for c in range(box[0]):
            x, y = coords[0] + c, coords[1] + r
            v = vals[y * dims[0] + x] if 0 <= x < dims[0] and 0 <= y < dims[1] else (nan_bits if fill else 0)
            img += [(v >> (8 * i)) & 255 for i in range(eb)]
    nb = len(img)
    sw = [0] * nb
    for b in range(nb):
        sw[dest(mode, b)] = img[b]
    words = [sum(sw[4 * i + j] << (8 * j) for j in range(4)) for i in range(nb // 4)]
    L = [f"// GENERATED by gen/tma_edges.py -- tile load, swizzle {mode}, box {box} at {coords} of {dims}",
         ".version 8.6\n.target sm_100a\n.address_size 64\n",
         f""".visible .entry k(.param .u64 ptm, .param .u64 po)
{{
    .reg .b64 %tm, %o, %mb, %st, %t, %sa, %oo; .reg .b32 %tid, %buf32, %bar32, %x; .reg .pred %q, %w;
    .shared .align 1024 .b8 buf[{(nb + 1023) // 1024 * 1024}];
    .shared .align 8 .b64 bar;
    ld.param.u64 %tm, [ptm]; ld.param.u64 %o, [po];
    mov.u32 %tid, %tid.x;
    setp.eq.u32 %q, %tid, 0;
    mov.u64 %mb, bar; mov.u32 %bar32, bar; mov.u32 %buf32, buf;
    @%q mbarrier.init.shared.b64 [%mb], 1;
    bar.sync 0;
    @%q mbarrier.arrive.expect_tx.shared.b64 %st, [%mb], {nb};
    @%q cp.async.bulk.tensor.2d.shared::cluster.global.tile.mbarrier::complete_tx::bytes [%buf32], [%tm, {{{h(coords)}}}], [%bar32];
    @%q mbarrier.try_wait.parity.shared.b64 %w, [%mb], 0;
    bar.sync 0;
    mul.wide.u32 %t, %tid, 4;
    mov.u64 %sa, buf; add.u64 %sa, %sa, %t; add.u64 %oo, %o, %t;"""]
    for i in range(0, nb // 4, 32):
        L.append(f"    ld.shared.b32 %x, [%sa+{4 * i}]; st.global.b32 [%oo+{4 * i}], %x;")
    L.append("    ret;\n}\n")
    gty = 'u16' if eb == 2 else 'u32'
    # (the fill mode rides in bits 8.. of the swizzle value)
    L.append(f".buffer G .{gty} = {{ {h(vals)} }};")
    L.append(f".tensormap TM {dtype} G .dims {{ {h(dims)} }} .strides {{ {dims[0] * eb} }} .box {{ {h(box)} }} "
             f".swizzle {CODES[mode] + (256 if fill else 0)} ;")
    L.append(f".buffer O .u32 [{len(words)}];\n.launch k <<< 1, 32 >>> (TM, O);\n.expect O .u32 = {{ {h(words)} }};")
    open(os.path.join(out, f"tma-edge-{name}.ptx"), "w").write("\n".join(L) + "\n")


def store_test(out, name, mode, dims, box, coords):
    """f16 tile store from a shared image: the in-bounds elements of the box land in G, the rest of G stays"""
    nb = box[0] * box[1] * 2
    sh = [random.getrandbits(8) for _ in range(nb)]
    g0 = [random.getrandbits(16) for _ in range(dims[0] * dims[1])]
    g = list(g0)
    for r in range(box[1]):
        for c in range(box[0]):
            x, y = coords[0] + c, coords[1] + r
            if 0 <= x < dims[0] and 0 <= y < dims[1]:
                b = (r * box[0] + c) * 2
                g[y * dims[0] + x] = sh[dest(mode, b)] | (sh[dest(mode, b + 1)] << 8)
    words = [sum(sh[4 * i + j] << (8 * j) for j in range(4)) for i in range(nb // 4)]
    L = [f"// GENERATED by gen/tma_edges.py -- tile store, swizzle {mode}, box {box} at {coords} of {dims}",
         ".version 8.6\n.target sm_100a\n.address_size 64\n",
         f""".visible .entry k(.param .u64 ptm, .param .u64 pi)
{{
    .reg .b64 %tm, %i, %t, %sa, %ii; .reg .b32 %tid, %buf32, %x; .reg .pred %q;
    .shared .align 1024 .b8 buf[{(nb + 1023) // 1024 * 1024}];
    ld.param.u64 %tm, [ptm]; ld.param.u64 %i, [pi];
    mov.u32 %tid, %tid.x; setp.eq.u32 %q, %tid, 0; mov.u32 %buf32, buf;
    mul.wide.u32 %t, %tid, 4; mov.u64 %sa, buf; add.u64 %sa, %sa, %t; add.u64 %ii, %i, %t;"""]
    for i in range(0, nb // 4, 32):
        L.append(f"    ld.global.b32 %x, [%ii+{4 * i}]; st.shared.b32 [%sa+{4 * i}], %x;")
    L.append(f"""    fence.proxy.async.shared::cta;
    bar.sync 0;
    @%q cp.async.bulk.tensor.2d.global.shared::cta.tile.bulk_group [%tm, {{{h(coords)}}}], [%buf32];
    @%q cp.async.bulk.commit_group;
    @%q cp.async.bulk.wait_group 0;
    ret;
}}
""")
    L.append(f".buffer G .u16 = {{ {h(g0)} }};")
    L.append(f".tensormap TM .f16 G .dims {{ {h(dims)} }} .strides {{ {dims[0] * 2} }} .box {{ {h(box)} }} "
             f".swizzle {CODES[mode]} ;")
    L.append(f".buffer I .u32 = {{ {h(words)} }};\n.launch k <<< 1, 32 >>> (TM, I);\n.expect G .u16 = {{ {h(g)} }};")
    open(os.path.join(out, f"tma-edge-{name}.ptx"), "w").write("\n".join(L) + "\n")


def red_test(out, name, op, dtype, dims, box, coords):
    """32-bit tile reduction (cp.reduce.async.bulk.tensor .add / .min) from a shared image without swizzle: the
    in-bounds elements of the box reduced into G, the rest of G unchanged"""
    nb = box[0] * box[1] * 4
    signed = dtype == '.s32'
    sh = [random.getrandbits(32) for _ in range(nb // 4)]
    g0 = [random.getrandbits(32) for _ in range(dims[0] * dims[1])]
    g = list(g0)
    sx = lambda v: v - (1 << 32) if signed and v >= 1 << 31 else v
    for r in range(box[1]):
        for c in range(box[0]):
            x, y = coords[0] + c, coords[1] + r
            if 0 <= x < dims[0] and 0 <= y < dims[1]:
                v, w = g[y * dims[0] + x], sh[r * box[0] + c]
                g[y * dims[0] + x] = (v + w) & 0xffffffff if op == 'add' else (v if sx(v) <= sx(w) else w)
    L = [f"// GENERATED by gen/tma_edges.py -- tile reduction .{op}{dtype}, box {box} at {coords} of {dims}",
         ".version 8.6\n.target sm_100a\n.address_size 64\n",
         f""".visible .entry k(.param .u64 ptm, .param .u64 pi)
{{
    .reg .b64 %tm, %i, %t, %sa, %ii; .reg .b32 %tid, %buf32, %x; .reg .pred %q;
    .shared .align 1024 .b8 buf[{(nb + 1023) // 1024 * 1024}];
    ld.param.u64 %tm, [ptm]; ld.param.u64 %i, [pi];
    mov.u32 %tid, %tid.x; setp.eq.u32 %q, %tid, 0; mov.u32 %buf32, buf;
    mul.wide.u32 %t, %tid, 4; mov.u64 %sa, buf; add.u64 %sa, %sa, %t; add.u64 %ii, %i, %t;"""]
    for i in range(0, nb // 4, 32):
        L.append(f"    ld.global.b32 %x, [%ii+{4 * i}]; st.shared.b32 [%sa+{4 * i}], %x;")
    L.append(f"""    fence.proxy.async.shared::cta;
    bar.sync 0;
    @%q cp.reduce.async.bulk.tensor.2d.global.shared::cta.{op}.tile.bulk_group [%tm, {{{h(coords)}}}], [%buf32];
    @%q cp.async.bulk.commit_group;
    @%q cp.async.bulk.wait_group 0;
    ret;
}}
""")
    L.append(f".buffer G .u32 = {{ {h(g0)} }};")
    L.append(f".tensormap TM {dtype} G .dims {{ {h(dims)} }} .strides {{ {dims[0] * 4} }} .box {{ {h(box)} }} .swizzle 0 ;")
    L.append(f".buffer I .u32 = {{ {h(sh)} }};\n.launch k <<< 1, 32 >>> (TM, I);\n.expect G .u32 = {{ {h(g)} }};")
    open(os.path.join(out, f"tma-edge-{name}.ptx"), "w").write("\n".join(L) + "\n")


out = sys.argv[1] if len(sys.argv) > 1 else "."
# rows of 60 f16 (7 chunks and 4 elements in bounds) of a box of 64, rows past dimension 1, NaN fill
load_test(out, 'ld-a32f', '128a32f', '.f16', True, [60, 40], [64, 16], [0, 30], 2, 0x7e00)
load_test(out, 'ld-128', '128', '.f16', False, [60, 40], [64, 16], [0, 30], 2)
# rows starting before the tensor (element by element)
load_test(out, 'ld-neg', '128a32f', '.f16', True, [60, 40], [64, 16], [-8, 2], 2, 0x7e00)
load_test(out, 'ld-32', '32', '.f32', True, [30, 20], [32, 8], [0, 15], 4, 0x7fc00000)
# stores: rows of 56 f16 (7 chunks) of a box of 64, past dimension 1 too
store_test(out, 'st-a32f', '128a32f', [56, 20], [64, 8], [0, 15])
store_test(out, 'st-128', '128', [56, 20], [64, 8], [0, 15])
store_test(out, 'st-none', 'none', [56, 20], [64, 8], [8, 3])
# reductions: rows past the end of both dimensions, and starting before the tensor
red_test(out, 'red-add', 'add', '.u32', [20, 12], [16, 8], [8, 6])
red_test(out, 'red-min', 'min', '.s32', [20, 12], [16, 8], [-5, -2])
